"""Build a self-contained, auditable Shadowrocket response script."""
from pathlib import Path
import hashlib
ROOT = Path(__file__).resolve().parent.parent
source = (ROOT / 'vendor/youtube.response.upstream.js').read_text()
patches = [
    ('function Br(l,e){Ni(l),Si(l),Pi(l,e)}', 'function Br(l,e){Ni(l)}'),
    ('e.blackEml.includes(i)||/shorts(?!_pivot_item)/.test(i)', 'e.blackEml.includes(i)'),
    ('Mi.find(r=>l.url.includes(r.path))', 'Mi.find(r=>l.url.split("?")[0].endsWith("/"+r.path))'),
    ('(F.request.headers["user-agent"]??F.request.headers["User-Agent"]).includes("music")', '(F.request.headers["user-agent"]??F.request.headers["User-Agent"]??"").includes("music")'),
    ('config:"YouTubeConfig",advertiseInfo:"YouTubeAdvertiseInfo"', 'config:"SRYouTubeAdblockConfig",advertiseInfo:"SRYouTubeAdblockAdvertiseInfo"'),
]
for old, new in patches:
    assert source.count(old) == 1, f'Upstream changed: {old}'
    source = source.replace(old, new)
prefix = '''// Adapted from Maasea/sgmodule (Apache-2.0); see NOTICE.md.
// Generated by tools/build.py. No third-party network calls.
(function () {
  const originalDone = $done;
  let completed = false;
  $done = function (result) {
    if (completed) return;
    completed = true;
    return originalDone(result);
  };
  try {
    const body = $response.body;
    // The upstream binary runtime requires Uint8Array, not a raw ArrayBuffer.
    if (body instanceof ArrayBuffer) $response.body = new Uint8Array(body);
    if (!($response.body instanceof Uint8Array)) { $done({}); return; }
'''
suffix = '''
  } catch (error) {
    console.log("YouTube Adblock: " + String(error));
    $done({});
  }
})();
'''
(ROOT / 'scripts/youtube.response.js').write_text(prefix + source + suffix)
print('Upstream SHA256:', hashlib.sha256((ROOT / 'vendor/youtube.response.upstream.js').read_bytes()).hexdigest())
print('Built scripts/youtube.response.js')
